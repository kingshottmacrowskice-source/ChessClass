export default function PixelPiece({
  type,
  color = "b",
}: {
  type: string;
  color?: string;
}) {
  const rows = shapes[type] || shapes.p,
    light = color === "w";
  return (
    <svg
      className="pixel-piece-art"
      viewBox="0 0 16 18"
      shapeRendering="crispEdges"
      aria-label={
        (light ? "白" : "黑") +
        (
          { p: "兵", r: "车", n: "马", b: "象", q: "后", k: "王" } as Record<
            string,
            string
          >
        )[type]
      }
      role="img"
    >
      {rows.flatMap((row, y) =>
        [...row].map((v, x) => {
          if (v !== "1") return null;
          const edge =
            x === 0 ||
            row[x - 1] !== "1" ||
            row[x + 1] !== "1" ||
            rows[y - 1]?.[x] !== "1" ||
            rows[y + 1]?.[x] !== "1";
          return (
            <rect
              key={y * 16 + x}
              x={x}
              y={y + 1}
              width="1"
              height="1"
              fill={
                edge
                  ? light
                    ? "#695647"
                    : "#a5bdd1"
                  : (x + y) % 7 === 0
                    ? light
                      ? "#e1c797"
                      : "#536c8c"
                    : light
                      ? "#fff2d3"
                      : "#24374f"
              }
            />
          );
        }),
      )}
    </svg>
  );
}
